CONTACT_RE = re.compile(
    r"(фио|телефон|название компани|контактн\w+ данн|оставьте заявку|оформите заявку|"
    r"оформить заявку|оставьте контакт|свяжитесь с менеджером|заполните форму)", re.I)
SENT_SPLIT = re.compile(r"(?<=[.!?])\s+(?=[А-ЯЁA-Z«])")


def build_messages(context: str, question: str, history: list, facts: list[str]) -> list[dict]:
    parts = [f"МАТЕРИАЛЫ БАЗЫ ЗНАНИЙ\n{context}"]
    if facts:
        parts.append("ИЗВЕСТНО О КЛИЕНТЕ\n" + "\n".join("- " + f for f in facts))
    if history:
        lines = []
        for role, text in history[-6:]:
            lines.append(("Пользователь: " if role == "user" else "Ассистент: ") + text)
        parts.append("ПРЕДЫДУЩИЕ РЕПЛИКИ\n" + "\n".join(lines))
    parts.append("ВОПРОС КЛИЕНТА\n" + question)
    parts.append("Дай ответ по формату: 3–4 предложения, 35–80 слов, одна строка, без просьбы контактов.")
    return [{"role": "system", "content": SYSTEM},
            {"role": "user", "content": "\n\n".join(parts)}]


def sentences(text: str) -> list[str]:
    return [s.strip() for s in SENT_SPLIT.split(text.strip()) if s.strip()]


def word_count(text: str) -> int:
    return len(re.findall(r"[0-9A-Za-zА-Яа-яЁё]+", text))


def clean(text: str) -> str:
    text = re.sub(r"", "", text or "", flags=re.S)
    text = re.sub(r"^\s*(Ответ|Answer)\s*:\s*", "", text.strip(), flags=re.I)
    text = re.sub(r"[*_`#>]+", "", text)
    text = re.sub(r"^\s*[-•]\s+", "", text, flags=re.M)
    text = " ".join(text.split())
    return text.strip().strip('"').strip()


def drop_contacts(text: str) -> str:
    kept = [s for s in sentences(text) if not CONTACT_RE.search(s)]
    return " ".join(kept) if kept else text


def trim(text: str) -> str:
    if word_count(text) <= config_hard_words():
        return text
    ss = sentences(text)
    if len(ss) <= 2:
        return text
    tail = ss[-1] if ss[-1].rstrip().endswith("?") else ""
    head: list[str] = []
    total = word_count(tail)
    for s in ss[:-1] if tail else ss:
        w = word_count(s)
        if total + w > config_target_words() and head:
            break
        head.append(s)
        total += w
    return " ".join(head + ([tail] if tail else []))


def config_target_words() -> int:
    import config
    return config.TARGET_WORDS


def config_hard_words() -> int:
    import config
    return config.HARD_WORDS


def postprocess(text: str) -> str:
    text = clean(text)
    text = drop_contacts(text)
    text = trim(text)
    text = " ".join(text.split())
    return text[:10000].strip()


