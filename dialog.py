def parse(text: str) -> dict:
    text = (text or "").strip()
    marks = list(ROLE_RE.finditer(text))
    if len(marks) >= 2:
        turns = []
        for i, m in enumerate(marks):
            end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            role = m.group(1).lower()
            body = text[m.end():end].strip()
            if body:
                turns.append(("user" if role in USER_ROLES else "assistant", body))
        last_user = next((t[1] for t in reversed(turns) if t[0] == "user"), text)
        history = turns[:-1] if turns and turns[-1][0] == "user" else turns
        return {"question": last_user, "history": history, "is_dialog": True,
                "user_text": " ".join(t[1] for t in turns if t[0] == "user")}
    return {"question": text, "history": [], "is_dialog": False, "user_text": text}


def extract_facts(user_text: str) -> list[str]:
    t = user_text.lower().replace("ё", "е")
    facts: list[str] = []

    for m in re.finditer(r"(\d[\d\s.,]{0,9})\s*(мвт|квт)\b(?!\s*[·*]?\s*ч)", t):
        val = m.group(1).strip().rstrip(".,")
        facts.append(f"заявленная мощность: {val} {m.group(2).upper()}")
        break
    for m in re.finditer(r"(\d[\d\s.,]{0,9})\s*(квт\s*[·*]?\s*ч|квтч|тыс\.?\s*квт)", t):
        facts.append(f"заявленное потребление: {m.group(1).strip()} {m.group(2)}")
        break
    for r in REGIONS:
        if re.search(r"\b" + r, t):
            facts.append(f"регион/локация упомянута: {r}")
            break
    for key, label in OBJECTS:
        if key in t:
            facts.append(f"тип объекта: {label}")
    for key, label in (("шифер", "шиферная кровля"), ("металлочерепиц", "металлочерепица"),
                       ("мягк", "мягкая кровля"), ("плоск", "плоская кровля"),
                       ("скат", "скатная кровля"), ("фасад", "фасад"), ("земл", "наземное размещение")):
        if key in t:
            facts.append(f"размещение/кровля: {label}")
            break
    for key, label in (("ночь", "ночная нагрузка"), ("вечер", "вечерняя нагрузка"),
                       ("днем", "дневная нагрузка"), ("днём", "дневная нагрузка"),
                       ("круглосуточ", "круглосуточная нагрузка"), ("смен", "сменный график")):
        if key in t:
            facts.append(f"профиль: {label}")
    for key, label in (("аскуэ", "есть АСКУЭ"), ("интервальн", "интервальный учёт"),
                       ("почасов", "почасовой учёт"), ("двухтариф", "двухтарифный прибор"),
                       ("однотариф", "однотарифный прибор"), ("многотариф", "многотарифный прибор")):
        if key in t:
            facts.append(f"учёт: {label}")
    m = re.search(r"(перв|втор|треть|четверт|пят|шест)\w*\s+(ценов\w*\s+)?категор", t)
    if m:
        facts.append(f"ценовая категория: {m.group(1)}ая")
    m = re.search(r"(\d+)\s*(магазин|склад|прибор|счетчик|счётчик|точек|точк)", t)
    if m:
        facts.append(f"количество: {m.group(1)} {m.group(2)}")

    seen, out = set(), []
    for f in facts:
        if f not in seen:
            seen.add(f)
            out.append(f)
    return out[:8]


def route_topics(question: str, user_text: str) -> list[str]:
    t = (question + " " + user_text).lower().replace("ё", "е")
    scores: dict[str, float] = {}
    for topic, keys in TOPIC_KEYWORDS.items():
        s = 0.0
        for k in keys:
            pat = k if k.startswith("\\b") else r"\b" + k
            if re.search(pat, t):
                s += 1.0
        if s:
            scores[topic] = s
    return [k for k, _ in sorted(scores.items(), key=lambda x: -x[1])[:4]]


